/** 依次把各组里原词（不区分大小写）还没出现过的术语接到 base 后面：先出现的原词保留其译法。 */
function withNewTerms(base: Term[], ...groups: Term[][]): Term[] {
  const seen = new Set(base.map((t) => t.source.toLowerCase()));
  const out = [...base];
  for (const t of groups.flat()) {
    const key = t.source.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(t);
  }
  return out;
}

